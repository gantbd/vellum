/// Diagnostic classification only; never used to settle an operation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Disposition {
    Completed,
    Refused,
    Failed,
    Unknown,
    Partial,
}

/// Closed, content-free fields: no source, paths, credentials or opaque handles.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Observation {
    pub boundary: Boundary,
    pub disposition: Disposition,
    /// None means unmeasured, never zero latency or a measured absence of work.
    pub service_time: Option<Duration>,
}

/// Whether this optional diagnostic record was retained.
pub use keystone_observe::Capture;

/// Bounded capture with drop-newest overload behavior and no record-time growth.
///
/// Construct before entering engine execution. Allocation failure is explicit;
/// `disabled()` requires no allocation. No deployment capacity is implied.
#[derive(Debug)]
pub struct Recorder {
    records: CaptureBuffer<Observation>,
    measurements: Option<Box<measurement::DiagnosticMeasurementsV1>>,
    native_timing: NativeTimingProfileV1,
}

impl Recorder {
    pub fn try_with_capacity(limit: usize) -> Result<Self, std::collections::TryReserveError> {
        // Vellum's existing zero-capacity profile means disabled, not overload.
        let records = if limit == 0 {
            CaptureBuffer::disabled()
        } else {
            CaptureBuffer::try_with_capacity(limit)?
        };
        Ok(Self {
            records,
            measurements: None,
            native_timing: NativeTimingProfileV1::Off,
        })
    }

    pub fn disabled() -> Self {
        Self {
            records: CaptureBuffer::disabled(),
            measurements: None,
            native_timing: NativeTimingProfileV1::Off,
        }
    }

    /// No callbacks, blocking, allocation, formatting or clock access.
    /// Callers must never branch engine authorization or settlement on this result.
    pub fn record(&mut self, observation: Observation) -> Capture {
        if let Some(m) = &mut self.measurements {
            m.increment(measurement::DiagnosticV1::Offered);
        }
        let capture = self.records.record(observation);
        if let Some(m) = &mut self.measurements {
            match capture {
                Capture::Recorded => m.increment(measurement::DiagnosticV1::Captured),
                Capture::Dropped => m.increment(measurement::DiagnosticV1::Dropped),
                Capture::Disabled => {}
            }
        }
        capture
    }

    /// Transfers one owned record. No subscriber runs within capture.
    pub fn pop_front(&mut self) -> Option<Observation> {
        let out = self.records.pop_front();
        if out.is_some()
            && let Some(m) = &mut self.measurements
        {
            m.increment(measurement::DiagnosticV1::Drained);
        }
        out
    }

    pub fn queued(&self) -> usize {
        self.records.queued()
    }
    pub fn capacity(&self) -> usize {
        self.records.capacity()
    }
    /// Cumulative since construction; saturates instead of wrapping.
    pub fn dropped(&self) -> u64 {
        self.records.dropped()
    }
    /// Separately bounded native counters, opt-in from construction. The existing
    /// boundary-marker queue shape and drop-newest behavior are unchanged.
    pub fn try_with_diagnostic_measurements(
        limit: usize,
        profile: measurement::DiagnosticMeasurementLimitsV1,
    ) -> Result<Self, measurement::MeasurementErrorV1> {
        let measurements = measurement::DiagnosticMeasurementsV1::new(profile)?;
        let mut recorder = Self::try_with_capacity(limit)
            .map_err(|_| measurement::MeasurementErrorV1::Capacity)?;
        recorder.measurements = Some(Box::new(measurements));
        Ok(recorder)
    }
    /// Privileged local producer snapshot, not recipient-authorized telemetry or
    /// engine traffic. Does not drain events or infer time/operation completion.
    pub fn diagnostic_measurements(
        &mut self,
    ) -> Result<Option<[measurement::MeasurementPointV1; 4]>, measurement::MeasurementErrorV1> {
        self.measurements.as_mut().map(|m| m.snapshot()).transpose()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recording_respects_the_shared_storage_ceiling() {
        let mut recorder = Recorder::try_with_capacity(2).unwrap();
        let observation = Observation {
            boundary: Boundary::Admission,
            disposition: Disposition::Refused,
            service_time: Some(Duration::ZERO),
        };
        for _ in 0..100 {
            recorder.record(observation);
        }
        assert_eq!(recorder.capacity(), 2);
        assert_eq!(recorder.queued(), 2);
        assert_eq!(recorder.dropped(), 98);
    }

    #[test]
    fn draining_reuses_capacity_and_preserves_fifo_and_cumulative_loss() {
        let mut recorder = Recorder::try_with_capacity(2).unwrap();
        let observation = Observation {
            boundary: Boundary::Publication,
            disposition: Disposition::Completed,
            service_time: Some(Duration::ZERO),
        };
        let next = Observation {
            disposition: Disposition::Unknown,
            ..observation
        };
        assert_eq!(recorder.record(observation), Capture::Recorded);
        assert_eq!(recorder.record(next), Capture::Recorded);
        assert_eq!(recorder.record(observation), Capture::Dropped);
        assert_eq!(recorder.pop_front(), Some(observation));
        assert_eq!(recorder.record(observation), Capture::Recorded);
        assert_eq!(recorder.pop_front(), Some(next));
        assert_eq!(recorder.pop_front(), Some(observation));
        assert_eq!(recorder.pop_front(), None);
        assert_eq!(recorder.capacity(), 2);
        assert_eq!(recorder.dropped(), 1);
    }
}
